import { Router, Request, Response } from "express";
import fs from "fs";
import path from "path";
import { Session } from "../models/Session";
import { Wallet } from "../models/Wallet";
import { runGenerate, getScriptsDir, isRunning } from "../lib/runner";
import { requireAuth } from "../middleware/requireAuth";
import { requirePlan } from "../middleware/requirePlan";
import { recordSessionAudit } from "../lib/sessionAudit";
import { parseWalletsCsv } from "../lib/walletsCsv";

const router = Router();

// POST /api/generate — spawn generate-wallets.ts
router.post("/", requireAuth, requirePlan, async (req: Request, res: Response) => {
  try {
    const { sessionId, privateKey, walletMode } = req.body as {
      sessionId: string;
      privateKey?: string;
      walletMode?: "HD_SINGLE_SEED" | "INDEPENDENT_SEEDS";
    };
    // Pool wallets are generated by the Managed Wallets API, never by the script.
    if ((walletMode as string | undefined) === "MANAGED_POOL") {
      return res.status(400).json({ error: "Use POST /api/admin/managed/sessions/:sessionId/generate for pool wallets" });
    }
    const resolvedWalletMode =
      walletMode === "HD_SINGLE_SEED" || walletMode === "INDEPENDENT_SEEDS"
        ? walletMode
        : "INDEPENDENT_SEEDS";

    if (!sessionId) return res.status(400).json({ error: "sessionId is required" });

    const session = await Session.findById(sessionId);
    if (!session) return res.status(404).json({ error: "Session not found" });

    if (!session.userId || session.userId.toString() !== req.user!._id.toString()) {
      return res.status(404).json({ error: "Session not found" });
    }

    if (isRunning(sessionId)) {
      return res.status(409).json({ error: "Generation already running for this session" });
    }

    await Session.update(sessionId, { status: "generating", startedAt: new Date() });
    await Wallet.deleteBySession(sessionId);
    await recordSessionAudit({
      userId: req.user!._id,
      sessionId,
      action: "GENERATE_STARTED",
      message: "Wallet generation started",
      details: { totalWallets: session.totalWallets },
    });

    const onFailed = async (err: unknown) => {
      console.error("[generate] error:", err);
      await Session.update(sessionId, { status: "error" });
      await recordSessionAudit({
        userId: req.user!._id,
        sessionId,
        action: "GENERATE_FAILED",
        message: "Wallet generation failed",
        details: { error: String(err) },
      });
    };

    runGenerate(
      sessionId,
      {
        privateKey,
        tokenAddress: session.tokenAddress,
        multisenderAddress: session.multisenderAddress,
        totalWallets: session.totalWallets,
        walletMode: resolvedWalletMode,
      },
      async (count) => {
        await Session.update(sessionId, { sentCount: count });
      },
      async (mnemonic) => {
        try {
          // Store mnemonic and import wallets from the CSV the script wrote
          await Session.update(sessionId, {
            status: "idle",
            masterMnemonic: mnemonic,
          });

          const csvPath = path.join(getScriptsDir(), "output", "wallets.csv");
          if (fs.existsSync(csvPath)) {
            // Only index, address and derivationPath leave the file; never the keys or seed phrases.
            const rows = parseWalletsCsv(fs.readFileSync(csvPath, "utf8"));
            await Wallet.insertMany(
              rows.map((row) => ({
                sessionId,
                index: row.index,
                address: row.address,
                derivationPath: row.derivationPath,
                amount: 0,
                amountWei: "0",
                packedHex: "0x",
                sent: false,
                failed: false,
              }))
            );
          }

          await Session.update(sessionId, { status: "idle" });
          await recordSessionAudit({
            userId: req.user!._id,
            sessionId,
            action: "GENERATE_COMPLETED",
            message: "Wallet generation completed",
            details: { importedWallets: session.totalWallets },
          });
        } catch (err) {
          await onFailed(err);
        }
      },
      onFailed
    );

    return res.json({ status: "started", sessionId });
  } catch (err) {
    console.error("[generate POST]", err);
    return res.status(500).json({ error: "Failed to start generation" });
  }
});

export default router;
